import { describe, it, expect, vi } from 'vitest';
import { ref } from 'vue';
import { useLyrics } from '@/composables/useLyrics';

describe('useLyrics', () => {
	it('parses LRC timestamps correctly and synchronizes active line', async () => {
		const localTimePos = ref(0);
		const { lyrics, currentLyricLine, loadLyrics } = useLyrics({ localTimePos });

		const lrcContent = `
[00:05.00]Primera línea del fogón
[00:15.50]Segunda línea con acordes
[00:30.00]Tercera línea final
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(lrcContent),
		} as unknown as Response);

		await loadLyrics('/music/cancion.mp3');

		expect(lyrics.value.length).toBe(3);
		expect(lyrics.value[0]).toEqual({ time: 5, text: 'Primera línea del fogón' });
		expect(lyrics.value[1]).toEqual({ time: 15.5, text: 'Segunda línea con acordes' });
		expect(lyrics.value[2]).toEqual({ time: 30, text: 'Tercera línea final' });

		// Before first line
		localTimePos.value = 2;
		expect(currentLyricLine.value).toBe(' ');

		// At 10s: first line active
		localTimePos.value = 10;
		expect(currentLyricLine.value).toBe('Primera línea del fogón');

		// At 20s: second line active
		localTimePos.value = 20;
		expect(currentLyricLine.value).toBe('Segunda línea con acordes');

		// At 35s: third line active
		localTimePos.value = 35;
		expect(currentLyricLine.value).toBe('Tercera línea final');
	});

	it('handles empty lyrics or 404 responses gracefully', async () => {
		const localTimePos = ref(10);
		const { lyrics, currentLyricLine, loadLyrics } = useLyrics({ localTimePos });

		global.fetch = vi.fn().mockResolvedValue({
			ok: false,
			status: 404,
		} as unknown as Response);

		await loadLyrics('/music/sin_letra.mp3');
		expect(lyrics.value).toEqual([]);
		expect(currentLyricLine.value).toBeNull();
	});

	it('skips web/HTTP streams for lyrics fetching', async () => {
		const localTimePos = ref(0);
		const { lyrics, loadLyrics } = useLyrics({ localTimePos });

		const fetchSpy = vi.fn();
		global.fetch = fetchSpy;

		await loadLyrics('https://youtube.com/watch?v=123');
		expect(fetchSpy).not.toHaveBeenCalled();
		expect(lyrics.value).toEqual([]);
	});

	it('handles instrumental pauses and inserts carpincho emoji for short gaps', async () => {
		const localTimePos = ref(0);
		const { lyrics, loadLyrics } = useLyrics({ localTimePos });

		const lrcContent = `
[00:05.00]Primera
[00:10.00]
[00:11.50]Segunda
[00:15.00]
[00:18.00]Tercera
[00:20.00]
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(lrcContent),
		} as unknown as Response);

		await loadLyrics('/music/instrumental.mp3');

		// Check the items
		// 10.0s gap to 11.5s is 1.5s -> '🦦'
		expect(lyrics.value.find((l) => l.time === 10)?.text).toBe('🦦');
		// 15.0s gap to 18.0s is 3.0s -> ' '
		expect(lyrics.value.find((l) => l.time === 15)?.text).toBe(' ');
		// 20.0s has no subsequent lines -> ' '
		expect(lyrics.value.find((l) => l.time === 20)?.text).toBe(' ');
	});

	it('parses ASS karaoke lyrics and computes wordbyword syllables accurately', async () => {
		const localTimePos = ref(0);
		const { lyrics, activeLyricLines, currentLyricLine, loadLyrics } = useLyrics({ localTimePos });

		const assContent = `[Script Info]
; Script generated by TTML to eLRC Converter
Title: Fito Páez - 11 Y 6
ScriptType: v4.00+

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:00.00,0:00:00.70,Default,,0,0,0,,{\\blur3}{\\kf12}11 {\\kf12}Y {\\kf12}6 {\\kf12}- {\\kf12}Fito {\\kf6}Paez
Dialogue: 0,0:00:00.70,0:00:04.10,Default,,0,0,0,,{\\blur3}{\\kf11}En {\\kf17}un {\\kf19}caf{\\kf51}é {\\kf24}se {\\kf47}vieron {\\kf67}por {\\kf100}casualidad
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(assContent),
		} as unknown as Response);

		await loadLyrics('/music/fito.mp3');

		expect(lyrics.value.length).toBe(2);

		// Línea 1
		const line1 = lyrics.value[0];
		expect(line1.time).toBe(0);
		expect(line1.endTime).toBe(0.7);
		expect(line1.text).toBe('11 Y 6 - Fito Paez');
		expect(line1.syllables).toBeDefined();
		expect(line1.syllables?.length).toBe(6);
		expect(line1.syllables?.[0]).toEqual({ text: '11 ', start: 0, end: 0.12 });
		expect(line1.syllables?.[1]).toEqual({ text: 'Y ', start: 0.12, end: 0.24 });

		// Línea 2: En un café se vieron por casualidad
		const line2 = lyrics.value[1];
		expect(line2.time).toBe(0.7);
		expect(line2.endTime).toBe(4.1);
		expect(line2.text).toBe('En un café se vieron por casualidad');
		expect(line2.syllables?.length).toBe(8);
		// En: start 0.70, duration 0.11 -> 0.81
		expect(line2.syllables?.[0]).toEqual({ text: 'En ', start: 0.7, end: 0.81 });
		// un: start 0.81, duration 0.17 -> 0.98
		expect(line2.syllables?.[1]).toEqual({ text: 'un ', start: 0.81, end: 0.98 });
		// caf: start 0.98, duration 0.19 -> 1.17
		expect(line2.syllables?.[2]).toEqual({ text: 'caf', start: 0.98, end: 1.17 });
		// é: start 1.17, duration 0.51 -> 1.68
		expect(line2.syllables?.[3]).toEqual({ text: 'é ', start: 1.17, end: 1.68 });

		// Sincronización en tiempo real
		localTimePos.value = 0.5;
		expect(activeLyricLines.value.length).toBe(1);
		expect(activeLyricLines.value[0].text).toBe('11 Y 6 - Fito Paez');
		expect(currentLyricLine.value).toBe('11 Y 6 - Fito Paez');

		localTimePos.value = 1.0;
		expect(activeLyricLines.value.length).toBe(1);
		expect(activeLyricLines.value[0].text).toBe('En un café se vieron por casualidad');
	});

	it('supports multiple simultaneous lines active at the same time', async () => {
		const localTimePos = ref(0);
		const { lyrics, activeLyricLines, currentLyricLine, loadLyrics } = useLyrics({ localTimePos });

		const simultaneousAss = `[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:10.00,0:00:15.00,Default,,0,0,0,,{\\kf50}Voz {\\kf50}principal
Dialogue: 0,0:00:12.00,0:00:16.00,Default,,0,0,0,,{\\kf50}Segunda {\\kf50}voz
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(simultaneousAss),
		} as unknown as Response);

		await loadLyrics('/music/dueto.mp3');
		expect(lyrics.value.length).toBe(2);

		// At 11s: solo la primera voz está activa
		localTimePos.value = 11;
		expect(activeLyricLines.value.length).toBe(1);
		expect(activeLyricLines.value[0].text).toBe('Voz principal');

		// At 13s: ambas líneas se reproducen simultáneamente
		localTimePos.value = 13;
		expect(activeLyricLines.value.length).toBe(2);
		expect(activeLyricLines.value.map((l) => l.text)).toEqual(['Voz principal', 'Segunda voz']);
		expect(currentLyricLine.value).toBe('Voz principal / Segunda voz');

		// At 15.5s: solo la segunda voz sigue activa
		localTimePos.value = 15.5;
		expect(activeLyricLines.value.length).toBe(1);
		expect(activeLyricLines.value[0].text).toBe('Segunda voz');

		// At 17s: ninguna está activa (outro tras el dueto, debe retornar silencio ' ' y no repetir 'Segunda voz')
		localTimePos.value = 17;
		expect(activeLyricLines.value.length).toBe(0);
		expect(currentLyricLine.value).toBe(' ');
	});

	it('returns silence for long gaps and carpincho emoji for short gaps in ASS lyrics', async () => {
		const localTimePos = ref(0);
		const { lyrics, activeLyricLines, currentLyricLine, loadLyrics } = useLyrics({ localTimePos });

		const assGaps = `[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:05.00,0:00:10.00,Default,,0,0,0,,{\\kf100}Primera {\\kf100}frase
Dialogue: 0,0:00:11.50,0:00:15.00,Default,,0,0,0,,{\\kf100}Segunda {\\kf100}frase
Dialogue: 0,0:00:25.00,0:00:30.00,Default,,0,0,0,,{\\kf100}Tercera {\\kf100}frase
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(assGaps),
		} as unknown as Response);

		await loadLyrics('/music/gaps.mp3');
		expect(lyrics.value.length).toBe(3);

		// Durante la primera frase (5s - 10s)
		localTimePos.value = 7;
		expect(activeLyricLines.value.length).toBe(1);
		expect(currentLyricLine.value).toBe('Primera frase');

		// Silencio corto entre frase 1 y 2 (10s a 11.5s -> gap = 1.5s): debe mostrar '🦦' y NO repetir la frase completa
		localTimePos.value = 10.5;
		expect(activeLyricLines.value.length).toBe(0);
		expect(currentLyricLine.value).toBe('🦦');

		// Durante la segunda frase (11.5s - 15s)
		localTimePos.value = 13;
		expect(activeLyricLines.value.length).toBe(1);
		expect(currentLyricLine.value).toBe('Segunda frase');

		// Silencio largo entre frase 2 y 3 (15s a 25s -> gap = 10s): debe mostrar silencio ' ' para volver al título
		localTimePos.value = 18;
		expect(activeLyricLines.value.length).toBe(0);
		expect(currentLyricLine.value).toBe(' ');

		// Durante la tercera frase (25s - 30s)
		localTimePos.value = 27;
		expect(activeLyricLines.value.length).toBe(1);
		expect(currentLyricLine.value).toBe('Tercera frase');

		// Tras finalizar la última frase (30s+ -> outro): silencio ' ' para volver al título
		localTimePos.value = 32;
		expect(activeLyricLines.value.length).toBe(0);
		expect(currentLyricLine.value).toBe(' ');
	});

	it('handles zero-duration syllables and timed space gaps properly (Imagine line)', async () => {
		const localTimePos = ref(0);
		const { lyrics, activeLyricLines, loadLyrics } = useLyrics({ localTimePos });

		const assContent = `[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:02:14.81,0:02:17.31,Default,,0,0,0,,{\\blur3}{\\kf0}A{\\k3} {\\kf121}brotherhood{\\k9} {\\kf22}of{\\k12} {\\kf70}man{\\k9} 
`;

		global.fetch = vi.fn().mockResolvedValue({
			ok: true,
			text: () => Promise.resolve(assContent),
		} as unknown as Response);

		await loadLyrics('/music/imagine.mp3');
		expect(lyrics.value.length).toBe(1);

		const line = lyrics.value[0];
		expect(line.text).toBe('A brotherhood of man');
		expect(line.syllables).toBeDefined();

		// Las palabras deben quedar separadas limpiamente con tiempos progresivos
		const words = line.syllables!.map((s) => s.text.trim());
		expect(words).toEqual(['A', 'brotherhood', 'of', 'man']);

		// La primera sílaba "A" no debe absorber toda la duración de la línea
		expect(line.syllables![0].start).toBe(134.81);
		expect(line.syllables![0].end).toBeLessThanOrEqual(134.85);

		expect(line.syllables![1].start).toBeGreaterThanOrEqual(134.81);
		expect(line.syllables![1].end).toBe(136.14);

		expect(line.syllables![2].start).toBe(136.14);
		expect(line.syllables![2].end).toBe(136.48);

		expect(line.syllables![3].start).toBe(136.48);
		expect(line.syllables![3].end).toBe(137.27);

		// A los 135.50s (2:15.50), "brotherhood" debe ser la sílaba activa, no "A"
		localTimePos.value = 135.5;
		expect(activeLyricLines.value.length).toBe(1);
		const activeSyls = activeLyricLines.value[0].syllables;
		const currentActive = activeSyls?.find((s) => localTimePos.value >= s.start && localTimePos.value < s.end);
		expect(currentActive?.text.trim()).toBe('brotherhood');

		// A los 136.20s, "of" debe ser la sílaba activa
		localTimePos.value = 136.2;
		const activeOf = activeSyls?.find((s) => localTimePos.value >= s.start && localTimePos.value < s.end);
		expect(activeOf?.text.trim()).toBe('of');

		// A los 136.60s, "man" debe ser la sílaba activa
		localTimePos.value = 136.6;
		const activeMan = activeSyls?.find((s) => localTimePos.value >= s.start && localTimePos.value < s.end);
		expect(activeMan?.text.trim()).toBe('man');
	});
});
